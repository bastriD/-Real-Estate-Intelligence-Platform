-- =============================================================================
-- 5. Commission grid evolution
--
-- Existing rows originate from the legacy migration.
--
-- They preserve the legacy numeric values but their original business meaning
-- is ambiguous. They MUST NOT silently become operational remuneration grids.
--
-- statut_usage:
--
--   HISTORIQUE = migrated / retained for traceability
--   APPROUVE    = explicitly approved for operational calculation
--
-- id_chasseur NULL represents the default grid.
--
-- Operational price interval convention:
--
--   montant_min is inclusive
--   montant_max is exclusive
--   montant_max NULL means no upper limit
--
-- Example:
--
--   [0, 200000)
--   [200000, 350000)
--   [350000, 500000)
-- =============================================================================

ALTER TABLE real_estate.bareme_commission
    ALTER COLUMN id_chasseur DROP NOT NULL;


ALTER TABLE real_estate.bareme_commission
    ADD COLUMN statut_usage VARCHAR(24)
        NOT NULL
        DEFAULT 'HISTORIQUE';


ALTER TABLE real_estate.bareme_commission
    ADD CONSTRAINT ck_bareme_commission_statut_usage
    CHECK (
        statut_usage IN (
            'HISTORIQUE',
            'APPROUVE'
        )
    );


-- The current legacy rows stay explicitly historical.
UPDATE real_estate.bareme_commission
SET statut_usage = 'HISTORIQUE';


CREATE INDEX idx_bareme_commission_selection
    ON real_estate.bareme_commission(
        id_chasseur,
        date_debut_validite,
        date_fin_validite,
        montant_min,
        montant_max
    )
    WHERE actif = TRUE
      AND statut_usage = 'APPROUVE';


CREATE INDEX idx_bareme_commission_defaut
    ON real_estate.bareme_commission(
        date_debut_validite,
        date_fin_validite,
        montant_min,
        montant_max
    )
    WHERE id_chasseur IS NULL
      AND actif = TRUE
      AND statut_usage = 'APPROUVE';


COMMENT ON COLUMN real_estate.bareme_commission.montant_min IS
    'Operational APPROUVE grids use an inclusive lower bound.';

COMMENT ON COLUMN real_estate.bareme_commission.montant_max IS
    'Operational APPROUVE grids use an exclusive upper bound; NULL means no upper bound.';

COMMENT ON COLUMN real_estate.bareme_commission.statut_usage IS
    'HISTORIQUE preserves migrated legacy values; APPROUVE is eligible for operational remuneration calculation.';


-- -----------------------------------------------------------------------------
-- Prevent overlapping approved commission-grid lines.
--
-- Overlap is checked for:
--
--   same hunter/default scope
--   overlapping validity period
--   overlapping price range
--
-- Hunter-specific and default grids may overlap each other deliberately:
-- a hunter-specific grid overrides the default grid in application logic.
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION real_estate.prevent_bareme_commission_overlap()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.actif
       AND NEW.statut_usage = 'APPROUVE'
    THEN

        IF EXISTS (
            SELECT 1
            FROM real_estate.bareme_commission b
            WHERE b.id_bareme <> NEW.id_bareme
              AND b.actif = TRUE
              AND b.statut_usage = 'APPROUVE'

              AND b.id_chasseur IS NOT DISTINCT FROM NEW.id_chasseur

              AND daterange(
                    b.date_debut_validite,
                    COALESCE(
                        b.date_fin_validite + 1,
                        'infinity'::date
                    ),
                    '[)'
                  )
                  &&
                  daterange(
                    NEW.date_debut_validite,
                    COALESCE(
                        NEW.date_fin_validite + 1,
                        'infinity'::date
                    ),
                    '[)'
                  )

              AND numrange(
                    b.montant_min,
                    b.montant_max,
                    '[)'
                  )
                  &&
                  numrange(
                    NEW.montant_min,
                    NEW.montant_max,
                    '[)'
                  )
        ) THEN
            RAISE EXCEPTION
                'Overlapping approved commission grid for hunter scope %',
                COALESCE(
                    NEW.id_chasseur::TEXT,
                    'DEFAULT'
                );
        END IF;

    END IF;

    RETURN NEW;
END;
$$;


CREATE TRIGGER trg_bareme_commission_no_overlap
BEFORE INSERT OR UPDATE
ON real_estate.bareme_commission
FOR EACH ROW
EXECUTE FUNCTION real_estate.prevent_bareme_commission_overlap();


