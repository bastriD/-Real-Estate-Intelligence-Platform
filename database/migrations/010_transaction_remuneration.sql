-- =============================================================================
-- 2. Versioned company-fee parameters
--
-- Business formula:
--
--     H = F + t * P
--
-- H = company fees
-- F = fixed component
-- t = percentage component
-- P = purchase price
--
-- Parameters are selected according to the authentic-deed date.
-- =============================================================================

CREATE TABLE real_estate.parametres_honoraires (
    id_parametres_honoraires BIGINT GENERATED BY DEFAULT AS IDENTITY,

    date_debut_validite DATE NOT NULL,
    date_fin_validite DATE NULL,

    montant_fixe NUMERIC(14, 2) NOT NULL,
    taux_pourcentage NUMERIC(9, 6) NOT NULL,

    actif BOOLEAN NOT NULL DEFAULT TRUE,

    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_parametres_honoraires
        PRIMARY KEY (id_parametres_honoraires),

    CONSTRAINT ck_parametres_honoraires_dates
        CHECK (
            date_fin_validite IS NULL
            OR date_fin_validite >= date_debut_validite
        ),

    CONSTRAINT ck_parametres_honoraires_montant_fixe
        CHECK (montant_fixe >= 0),

    CONSTRAINT ck_parametres_honoraires_taux
        CHECK (
            taux_pourcentage >= 0
            AND taux_pourcentage <= 1
        )
);


CREATE INDEX idx_parametres_honoraires_validite
    ON real_estate.parametres_honoraires(
        date_debut_validite,
        date_fin_validite
    );

CREATE INDEX idx_parametres_honoraires_actif
    ON real_estate.parametres_honoraires(actif)
    WHERE actif = TRUE;


-- -----------------------------------------------------------------------------
-- Prevent overlapping active company-fee configurations.
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION real_estate.prevent_parametres_honoraires_overlap()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.actif THEN

        IF EXISTS (
            SELECT 1
            FROM real_estate.parametres_honoraires p
            WHERE p.id_parametres_honoraires <> NEW.id_parametres_honoraires
              AND p.actif = TRUE
              AND daterange(
                    p.date_debut_validite,
                    COALESCE(
                        p.date_fin_validite + 1,
                        'infinity'::date
                    ),
                    '[)'
                  )
                  &&
                  daterange(
                    NEW.date_debut_validite,
                    COALESCE(
                        NEW.date_fin_validite + 1,
                        'infinity'::date
                    ),
                    '[)'
                  )
        ) THEN
            RAISE EXCEPTION
                'Overlapping active company-fee parameter period';
        END IF;

    END IF;

    RETURN NEW;
END;
$$;


CREATE TRIGGER trg_parametres_honoraires_no_overlap
BEFORE INSERT OR UPDATE
ON real_estate.parametres_honoraires
FOR EACH ROW
EXECUTE FUNCTION real_estate.prevent_parametres_honoraires_overlap();


-- =============================================================================
-- 3. Versioned remuneration/performance parameters
--
-- These values are parameters, not hard-coded business rules.
--
-- The five mandatory business criteria remain:
--
--   - delay Mandat -> authentic deed
--   - exclusivity
--   - successful sales
--   - signed Mandats
--   - visits before purchase
--
-- This table contains the configurable weights and modulation rules.
-- =============================================================================

CREATE TABLE real_estate.parametres_remuneration (
    id_parametres_remuneration BIGINT GENERATED BY DEFAULT AS IDENTITY,

    date_debut_validite DATE NOT NULL,
    date_fin_validite DATE NULL,

    fenetre_mois INTEGER NOT NULL,

    poids_delai NUMERIC(7, 6) NOT NULL,
    poids_exclusivite NUMERIC(7, 6) NOT NULL,
    poids_ventes NUMERIC(7, 6) NOT NULL,
    poids_mandats NUMERIC(7, 6) NOT NULL,
    poids_visites NUMERIC(7, 6) NOT NULL,

    note_exclusif NUMERIC(5, 2) NOT NULL,
    note_non_exclusif NUMERIC(5, 2) NOT NULL,

    points_par_vente NUMERIC(5, 2) NOT NULL,
    points_par_mandat NUMERIC(5, 2) NOT NULL,

    taux_anciennete_par_annee NUMERIC(9, 6) NOT NULL,
    plafond_anciennete NUMERIC(9, 6) NOT NULL,

    score_pivot NUMERIC(5, 2) NOT NULL,
    amplitude_performance NUMERIC(9, 6) NOT NULL,

    taux_plancher NUMERIC(9, 6) NOT NULL,
    taux_plafond NUMERIC(9, 6) NOT NULL,

    actif BOOLEAN NOT NULL DEFAULT TRUE,

    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_parametres_remuneration
        PRIMARY KEY (id_parametres_remuneration),

    CONSTRAINT ck_parametres_remuneration_dates
        CHECK (
            date_fin_validite IS NULL
            OR date_fin_validite >= date_debut_validite
        ),

    CONSTRAINT ck_parametres_remuneration_fenetre
        CHECK (fenetre_mois > 0),

    CONSTRAINT ck_parametres_remuneration_poids
        CHECK (
            poids_delai >= 0
            AND poids_exclusivite >= 0
            AND poids_ventes >= 0
            AND poids_mandats >= 0
            AND poids_visites >= 0
            AND (
                poids_delai
                + poids_exclusivite
                + poids_ventes
                + poids_mandats
                + poids_visites
            ) = 1.000000
        ),

    CONSTRAINT ck_parametres_remuneration_notes
        CHECK (
            note_exclusif BETWEEN 0 AND 100
            AND note_non_exclusif BETWEEN 0 AND 100
        ),

    CONSTRAINT ck_parametres_remuneration_points
        CHECK (
            points_par_vente >= 0
            AND points_par_mandat >= 0
        ),

    CONSTRAINT ck_parametres_remuneration_anciennete
        CHECK (
            taux_anciennete_par_annee >= 0
            AND plafond_anciennete >= 0
            AND plafond_anciennete <= 1
        ),

    CONSTRAINT ck_parametres_remuneration_score_pivot
        CHECK (score_pivot BETWEEN 0 AND 100),

    CONSTRAINT ck_parametres_remuneration_amplitude
        CHECK (
            amplitude_performance >= 0
            AND amplitude_performance <= 1
        ),

    CONSTRAINT ck_parametres_remuneration_taux
        CHECK (
            taux_plancher >= 0
            AND taux_plafond <= 1
            AND taux_plancher <= taux_plafond
        )
);


CREATE INDEX idx_parametres_remuneration_validite
    ON real_estate.parametres_remuneration(
        date_debut_validite,
        date_fin_validite
    );

CREATE INDEX idx_parametres_remuneration_actif
    ON real_estate.parametres_remuneration(actif)
