-- =============================================================================
-- Migration 010
-- Transaction and remuneration foundation
--
-- Business flow:
--
--   Mandat
--      |
--      v
--   Vente / acte authentique
--      |
--      v
--   Calcul de remuneration
--      |
--      v
--   Paiement
--
-- Goals:
--   - represent the completed sale independently from the payment lifecycle;
--   - preserve the Mandat / Bien / Presentation / hunter context of the sale;
--   - version company-fee parameters;
--   - version remuneration-performance parameters;
--   - support default and hunter-specific commission grids;
--   - prevent migrated legacy rates from being silently used as approved
--     operational remuneration grids;
--   - freeze all material inputs and outputs of a remuneration calculation;
--   - preserve all existing data and columns.
--
-- Important:
--   The numeric values proposed in the teaching material
--   (3000 EUR + 2.5%, commission bands, weights, modulation, etc.)
--   are configuration decisions, not immutable business rules.
--
--   This migration therefore creates the structures but DOES NOT seed those
--   example parameter values as production configuration.
-- =============================================================================


-- =============================================================================
-- 1. Completed transaction / sale
--
-- A sale is created when an authentic deed is signed.
--
-- id_presentation and id_bien are nullable deliberately:
--
--   - an exclusive Mandat may still remunerate the hunter when the client
--     found the property independently;
--   - a transaction originating outside the internal recommendation flow
--     may therefore have no internal Presentation.
--
-- id_mandat_periode identifies the contractual period giving entitlement
-- when such a valid period exists at the deed date.
-- =============================================================================

CREATE TABLE real_estate.vente (
    id_vente BIGINT GENERATED BY DEFAULT AS IDENTITY,

    id_mandat BIGINT NOT NULL,
    id_mandat_periode BIGINT NULL,

    id_presentation BIGINT NULL,
    id_bien BIGINT NULL,

    id_chasseur_beneficiaire BIGINT NULL,

    origine_vente VARCHAR(32) NOT NULL,

    date_acte_authentique DATE NOT NULL,
    montant_achat NUMERIC(14, 2) NOT NULL,

    date_creation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_vente
        PRIMARY KEY (id_vente),

    CONSTRAINT fk_vente_mandat
        FOREIGN KEY (id_mandat)
        REFERENCES real_estate.mandat(id_mandat)
        ON DELETE RESTRICT,

    CONSTRAINT fk_vente_mandat_periode
        FOREIGN KEY (id_mandat_periode)
        REFERENCES real_estate.mandat_periode(id_mandat_periode)
        ON DELETE RESTRICT,

    CONSTRAINT fk_vente_presentation
        FOREIGN KEY (id_presentation)
        REFERENCES real_estate.presentation(id_presentation)
        ON DELETE RESTRICT,

    CONSTRAINT fk_vente_bien
        FOREIGN KEY (id_bien)
        REFERENCES real_estate.bien(id_bien)
        ON DELETE RESTRICT,

    CONSTRAINT fk_vente_chasseur_beneficiaire
        FOREIGN KEY (id_chasseur_beneficiaire)
        REFERENCES real_estate.chasseur(id_chasseur)
        ON DELETE RESTRICT,

    CONSTRAINT ck_vente_origine
        CHECK (
            origine_vente IN (
                'CHASSEUR',
                'CLIENT_SEUL',
                'AUTRE_AGENCE'
            )
        ),

    CONSTRAINT ck_vente_montant_achat
        CHECK (montant_achat > 0)
);


